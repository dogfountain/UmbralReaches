def build_wall():
    import r37_wall as WALL
    importlib.reload(WALL)
    stone = L.ashlar("R37_WallStone", 4101)
    dark = L.flat("R37_Dark", (0.01, 0.01, 0.012), 1.0)
    wood = L.pbr("R37_GateWood", L.tex_planks(512, 3702), 2.4)
    iron = L.flat("R37_Iron", (0.08, 0.075, 0.07), 0.55, 0.85)
    mats = {"stone": stone, "dark": dark, "wood": wood, "iron": iron}
    objs = []
    WALL.build(mats, objs, DATA, PREVIEW)
    L.export(os.path.join(L.MODEL_DIR, "r37_south_wall.glb"), objs)
    if PREVIEW:
        os.makedirs(PREVIEW, exist_ok=True)
        WALL.previews(objs, PREVIEW)


def place_row(objs, order, step):
    x = 0.0
    for name in order:
        for o in objs:
            if o.name == name:
                o.location = G((x, 0, 0))
                x += step
                break


